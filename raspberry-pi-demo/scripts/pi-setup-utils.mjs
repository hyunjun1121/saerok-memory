import { chmod, mkdir, readFile, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const MINIMUM_NODE = Object.freeze({ major: 24, minor: 19, patch: 0 });

function parseNodeVersion(value) {
  const match = /^v?(\d+)\.(\d+)\.(\d+)$/.exec(String(value).trim());
  if (!match) {
    return null;
  }
  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    patch: Number(match[3]),
  };
}

export function isSupportedNodeVersion(value) {
  const parsed = parseNodeVersion(value);
  if (!parsed || parsed.major !== MINIMUM_NODE.major) {
    return false;
  }
  if (parsed.minor !== MINIMUM_NODE.minor) {
    return parsed.minor > MINIMUM_NODE.minor;
  }
  return parsed.patch >= MINIMUM_NODE.patch;
}

export function assertSupportedNodeVersion(value) {
  if (!isSupportedNodeVersion(value)) {
    throw new Error(
      `Node.js >=24.19.0 <25 is required; detected ${String(value).trim() || "unknown"}.`,
    );
  }
}

function validateBlockId(blockId) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(blockId)) {
    throw new Error(`Invalid managed block id: ${blockId}`);
  }
}

function markers(blockId) {
  validateBlockId(blockId);
  return {
    begin: `# BEGIN HARU MANAGED: ${blockId}`,
    end: `# END HARU MANAGED: ${blockId}`,
  };
}

function countOccurrences(value, search) {
  return value.split(search).length - 1;
}

function normalizeSource(value) {
  return value.replace(/\r\n/g, "\n");
}

export function setManagedBlock(source, blockId, command) {
  const normalized = normalizeSource(source);
  const { begin, end } = markers(blockId);
  if (!command || /[\r\n\0]/.test(command)) {
    throw new Error("Managed command must be one non-empty line.");
  }

  const beginCount = countOccurrences(normalized, begin);
  const endCount = countOccurrences(normalized, end);
  if (beginCount !== endCount || beginCount > 1) {
    throw new Error(`Malformed managed block: ${blockId}`);
  }

  const block = `${begin}\n# Generated by Haru setup; edit through scripts, not here.\n${command}\n${end}`;
  if (beginCount === 0) {
    const base = normalized.replace(/\s*$/, "");
    return base ? `${base}\n\n${block}\n` : `${block}\n`;
  }

  const start = normalized.indexOf(begin);
  const finish = normalized.indexOf(end, start) + end.length;
  return `${normalized.slice(0, start)}${block}${normalized.slice(finish)}`.replace(/\s*$/, "\n");
}

export function removeManagedBlock(source, blockId) {
  const normalized = normalizeSource(source);
  const { begin, end } = markers(blockId);
  const beginCount = countOccurrences(normalized, begin);
  const endCount = countOccurrences(normalized, end);
  if (beginCount !== endCount || beginCount > 1) {
    throw new Error(`Malformed managed block: ${blockId}`);
  }
  if (beginCount === 0) {
    return normalized;
  }

  const start = normalized.indexOf(begin);
  const finish = normalized.indexOf(end, start) + end.length;
  const before = normalized.slice(0, start).replace(/[ \t]*\n?$/, "");
  const after = normalized.slice(finish).replace(/^\s*/, "");
  if (before && after) {
    return `${before}\n\n${after}`.replace(/\s*$/, "\n");
  }
  return `${before || after}`.replace(/\s*$/, before || after ? "\n" : "");
}

export function hasManagedBlock(source, blockId) {
  const normalized = normalizeSource(source);
  const { begin, end } = markers(blockId);
  const beginCount = countOccurrences(normalized, begin);
  const endCount = countOccurrences(normalized, end);
  if (beginCount !== endCount || beginCount > 1) {
    throw new Error(`Malformed managed block: ${blockId}`);
  }
  return beginCount === 1;
}

async function writeAtomically(filePath, content) {
  const directory = path.dirname(filePath);
  await mkdir(directory, { recursive: true });
  let mode = 0o600;
  try {
    mode = (await stat(filePath)).mode & 0o777;
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }
  const temporaryPath = `${filePath}.haru-${process.pid}.tmp`;
  await writeFile(temporaryPath, content, { encoding: "utf8", mode });
  await chmod(temporaryPath, mode);
  await rename(temporaryPath, filePath);
}

async function readOptional(filePath) {
  try {
    return await readFile(filePath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") {
      return "";
    }
    throw error;
  }
}

async function runCli() {
  const [command, ...args] = process.argv.slice(2);
  if (command === "check-node" && args.length === 1) {
    assertSupportedNodeVersion(args[0]);
    process.stdout.write(`${args[0]}\n`);
    return;
  }
  if (command === "block-set" && args.length === 3) {
    const [filePath, blockId, managedCommand] = args;
    await writeAtomically(filePath, setManagedBlock(await readOptional(filePath), blockId, managedCommand));
    return;
  }
  if (command === "block-remove" && args.length === 2) {
    const [filePath, blockId] = args;
    await writeAtomically(filePath, removeManagedBlock(await readOptional(filePath), blockId));
    return;
  }
  if (command === "block-status" && args.length === 2) {
    const [filePath, blockId] = args;
    process.stdout.write(hasManagedBlock(await readOptional(filePath), blockId) ? "enabled\n" : "disabled\n");
    return;
  }
  throw new Error(
    "Usage: pi-setup-utils.mjs check-node VERSION | block-set FILE ID COMMAND | block-remove FILE ID | block-status FILE ID",
  );
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  runCli().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
