export type UiCopyKey = keyof (typeof uiCopy)["ko"];

export function getAllUiCopyValues(language: OfflineLanguage): readonly string[] {
  return Object.values(uiCopy[language]);
}

export function getBuildLanguage(): OfflineLanguage {
  return import.meta.env.VITE_HARU_MARKET === "jp" ? "ja" : "ko";
}

export function getUiCopy(
  language: OfflineLanguage,
  key: UiCopyKey,
  values: Record<string, string | number> = {},
): string {
  let value: string = uiCopy[language][key];
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(`{{${name}}}`, String(replacement));
  }
  return value;
}
